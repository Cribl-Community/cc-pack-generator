import { createWriteStream } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pipeline } from 'node:stream/promises';
import { createAppPack } from './pkgutil.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = join(__dirname, '..');
const buildOutDir = join(rootDir, 'build');
const packageJsonPath = join(rootDir, 'package.json');
const semverPattern = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;

function parseVersion(version) {
  const match = semverPattern.exec(version);
  if (!match) {
    throw new Error(`Invalid version "${version}". Expected X.Y.Z.`);
  }
  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    patch: Number(match[3]),
  };
}

function formatVersion(version) {
  return `${version.major}.${version.minor}.${version.patch}`;
}

export function parsePackageArgs(args) {
  let bump = 'patch';
  let explicitVersion;
  let noBump = false;
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === '--no-bump') {
      noBump = true;
    } else if (arg === '--minor') {
      bump = 'minor';
    } else if (arg === '--major') {
      bump = 'major';
    } else if (arg === '--version') {
      explicitVersion = args[i + 1];
      i += 1;
      if (!explicitVersion) {
        throw new Error('--version requires a value in X.Y.Z format.');
      }
    } else if (arg.startsWith('--version=')) {
      explicitVersion = arg.slice('--version='.length);
      if (!explicitVersion) {
        throw new Error('--version requires a value in X.Y.Z format.');
      }
    } else {
      throw new Error(`Unknown package option "${arg}". Use --no-bump, --minor, --major, or --version X.Y.Z.`);
    }
  }
  // Asking for both is a contradiction, and silently honouring one of them is
  // how you ship the version you did not mean to.
  if (noBump && (explicitVersion || args.some(a => a === '--minor' || a === '--major'))) {
    throw new Error('--no-bump cannot be combined with --minor, --major, or --version.');
  }
  return { bump, explicitVersion, noBump };
}

/**
 * Which version this package gets, and whether package.json must be rewritten
 * to say so.
 *
 * `--no-bump` packages the version already in package.json and returns
 * `write: false` — the file must come out BYTE-IDENTICAL. Re-serializing it
 * with the same version is not the same thing: it would reformat whatever the
 * working tree holds and turn a packaging step into a source edit.
 *
 * @returns {{ version: string, write: boolean }}
 */
export function resolvePackageVersion(currentVersion, args) {
  const { bump, explicitVersion, noBump } = parsePackageArgs(args);
  if (noBump) {
    parseVersion(currentVersion);
    return { version: currentVersion, write: false };
  }
  if (explicitVersion) {
    parseVersion(explicitVersion);
    return { version: explicitVersion, write: true };
  }

  const version = parseVersion(currentVersion);
  if (bump === 'major') {
    return { version: formatVersion({ major: version.major + 1, minor: 0, patch: 0 }), write: true };
  }
  if (bump === 'minor') {
    return { version: formatVersion({ major: version.major, minor: version.minor + 1, patch: 0 }), write: true };
  }
  return { version: formatVersion({ major: version.major, minor: version.minor, patch: version.patch + 1 }), write: true };
}

async function main() {
  const packageInfo = JSON.parse(await readFile(packageJsonPath, 'utf8'));
  const { version, write } = resolvePackageVersion(packageInfo.version || '0.0.0', process.argv.slice(2));
  packageInfo.version = version;
  if (write) {
    await writeFile(packageJsonPath, `${JSON.stringify(packageInfo, null, 2)}\n`);
  }

  const tgzName = `${packageInfo.name || 'app'}-${packageInfo.version}.tgz`;
  const tgzPath = join(buildOutDir, tgzName);
  await mkdir(buildOutDir, { recursive: true });
  // A Cribl-Community build (name `cc-…`, generated by scripts/publish-community.mjs)
  // ships its README and LICENSE at the pack root, where the app catalog reads
  // them. The monorepo's own README is a developer document, so it stays out.
  const community = String(packageInfo.name || '').startsWith('cc-');
  const { closePromise, stdout } = await createAppPack(community
    ? { readmePath: join(rootDir, 'README.md'), licensePath: join(rootDir, 'LICENSE') }
    : false);
  await Promise.all([ pipeline(stdout, createWriteStream(tgzPath)), closePromise ]);

  console.log(`\nPackage created: ${tgzPath}`);
}

// Importable without packaging anything: the version rules above are tested
// directly, and this file's main effect is to REWRITE package.json.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
